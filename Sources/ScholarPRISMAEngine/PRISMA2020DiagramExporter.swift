    /// Exports screened studies into RIS format with `KW  - PRISMA_INCLUDED` / `KW  - PRISMA_EXCLUDED` tags for Zotero/EndNote.
    public func exportRISDecisions(studies: [ScreeningStudyRecord]) -> String {
        var lines: [String] = []
        for s in studies {
            let finalVote = s.adjudicatedDecision ?? s.reviewerADecision
            lines.append("TY  - JOUR")
            lines.append("ID  - \(s.citeKey)")
            lines.append("TI  - \(s.title)")
            for author in s.authorsLine.split(separator: ";").map({ $0.trimmingCharacters(in: .whitespaces) }) where !author.isEmpty {
                lines.append("AU  - \(author)")
            }
            lines.append("PY  - \(s.year)")
            lines.append("JO  - \(s.venue)")
            if let doi = s.doi {
                lines.append("DO  - \(doi)")
            }
            lines.append("AB  - \(s.abstractText)")
            if let vote = finalVote {
                lines.append("KW  - PRISMA_\(vote.summaryLabel)")
            }
            lines.append("ER  - ")
            lines.append("")
        }
        return lines.joined(separator: "\n")
    }

    private func escapeLaTeX(_ s: String) -> String {
        s.replacingOccurrences(of: "_", with: "\\_")
            .replacingOccurrences(of: "&", with: "\\&")
            .replacingOccurrences(of: "%", with: "\\%")
    }

    private func escapeXML(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
    }
}
