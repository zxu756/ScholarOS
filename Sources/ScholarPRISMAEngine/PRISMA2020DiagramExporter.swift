    /// Exports a publication-ready LaTeX `tikzpicture` PRISMA 2020 Flow Diagram.
    public func exportLaTeXTikZ(metrics: PRISMA2020SummaryMetrics, reviewTitle: String) -> String {
        let reasonLines = metrics.fullTextExcludedByReason
            .sorted { $0.key < $1.key }
            .map { "\\quad \\texttt{\(escapeLaTeX($0.key))}: \( $0.value )" }
            .joined(separator: " \\\\\n        ")
        let totalFTExcluded = metrics.fullTextExcludedByReason.values.reduce(0, +)

        return """
        % Generated by ScholarOS PRISMA 2020 Engine — \(escapeLaTeX(reviewTitle))
        \\begin{tikzpicture}[
            node distance=1.15cm and 2.4cm,
            prismabox/.style={rectangle, rounded corners=2pt, draw=black!75, thick, fill=white, text width=6.2cm, minimum height=1.2cm, align=left, font=\\small},
            sidebox/.style={rectangle, rounded corners=2pt, draw=black!55, fill=black!3, text width=5.6cm, minimum height=1.1cm, align=left, font=\\footnotesize},
            arrow/.style={-Latex, thick, draw=black!75}
        ]
        \\node[prismabox] (id) {\\textbf{Identification}\\\\Databases ($n = \(metrics.databaseRecordsIdentified)$)\\\\Registers ($n = \(metrics.registerRecordsIdentified)$)};
        \\node[sidebox, right=of id] (dup) {Records removed before screening:\\\\Duplicates removed ($n = \(metrics.duplicateRecordsRemoved)$)};
        \\node[prismabox, below=of id] (scr) {\\textbf{Title \\& Abstract Screening}\\\\Records screened ($n = \(metrics.recordsScreenedTitleAbstract)$)\\\\$\\kappa = \(String(format: "%.3f", metrics.cohensKappa))$, PABAK $= \(String(format: "%.3f", metrics.pabakScore))$};
        \\node[sidebox, right=of scr] (taex) {Records excluded at Title/Abstract\\\\($n = \(metrics.recordsExcludedTitleAbstract)$)};
        \\node[prismabox, below=of scr] (ret) {\\textbf{Retrieval}\\\\Reports sought for retrieval ($n = \(metrics.reportsSoughtForRetrieval)$)};
        \\node[sidebox, right=of ret] (notret) {Reports not retrieved\\\\($n = \(metrics.reportsNotRetrieved)$)};
        \\node[prismabox, below=of ret] (elig) {\\textbf{Full-Text Eligibility}\\\\Reports assessed ($n = \(metrics.fullTextAssessed)$)};
        \\node[sidebox, right=of elig] (ftex) {Full-text reports excluded ($n = \(totalFTExcluded)$):\\\\
        \(reasonLines.isEmpty ? "\\quad None ($n = 0$)" : reasonLines)};
        \\node[prismabox, fill=green!6, below=of elig] (inc) {\\textbf{Included}\\\\Studies included in synthesis ($n = \(metrics.finalIncludedStudies)$)};

        \\draw[arrow] (id) -- (dup);
        \\draw[arrow] (id) -- (scr);
        \\draw[arrow] (scr) -- (taex);
        \\draw[arrow] (scr) -- (ret);
        \\draw[arrow] (ret) -- (notret);
        \\draw[arrow] (ret) -- (elig);
        \\draw[arrow] (elig) -- (ftex);
        \\draw[arrow] (elig) -- (inc);
        \\end{tikzpicture}
        """
    }

